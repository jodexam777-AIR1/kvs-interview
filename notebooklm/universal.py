def art_bounds(cid):
    a=s.find(f'<article class="card'); i=s.find(f'data-id="{cid}"')
    st=s.rfind('<article',0,i); en=s.find('</article>',i)+len('</article>')
    return st,en

def slot(label,cls): return f'<span class="n slot {cls}">{label}</span>'
for cid in FULL+SHORT:
    st,en=art_bounds(cid); A=s[st:en]
    A=A.replace('<span class="lab">पहली पंक्ति</span>','<span class="lab">हाँ — पहली पंक्ति</span>',1)
    A=A.replace('<span class="lab">आख़िरी पंक्ति</span>','<span class="lab">बच्चा — आख़िरी पंक्ति</span>',1)
    assert 'हाँ — पहली पंक्ति' in A and 'बच्चा — आख़िरी पंक्ति' in A, cid
    if cid in FIRST:
        A=re.sub(r'(<div class="row first"><span class="lab">हाँ — पहली पंक्ति</span><p>).*?(</p>)', lambda m: m.group(1)+FIRST[cid]+m.group(2), A, count=1)
    if cid in FULL:
        par,hal=cues[cid]
        keys=(f'<div class="row keys"><span class="lab">पर → हल</span><ol class="beats">'
              f'<li>{slot("पर","s2")}<span class="t">{par}</span></li><li>{slot("हल","s3")}<span class="t">{hal}</span></li></ol></div>')
        A,n=re.subn(r'<div class="row keys">.*?</ol></div>', lambda m: keys, A, count=1, flags=re.S)
        assert n==1, cid
    else:
        A=A.replace('<span class="lab">चाबी — इसी क्रम में</span>','<span class="lab">छोटा रूप — बीच में बस इतना</span>',1)
    if cid in ANS:
        i=A.find('<div class="ans">'); j=A.find('</div>',i)
        body=A[i:j]
        for o,nw in ANS[cid]:
            assert body.count(o)==1,(cid,o[:40]); body=body.replace(o,nw)
        A=A[:i]+body+A[j:]
    s=s[:st]+A+s[en:]

